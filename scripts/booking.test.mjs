import test from 'node:test';
import assert from 'node:assert/strict';
import {createHmac} from 'node:crypto';
import {localDb} from './local-db.mjs';
import worker from '../dist/server/index.js';
test('operator release, seat hold, payment capture, delayed webhook and receipt',async t=>{
 const env={DB:localDb(),PREVIEW_OWNER_EMAIL:'owner@example.test',RAZORPAY_KEY_ID:'rzp_test_example',RAZORPAY_KEY_SECRET:'test-key',RAZORPAY_WEBHOOK_SECRET:'test-webhook'};
 const head={'oai-authenticated-user-id':'owner','oai-authenticated-user-email':env.PREVIEW_OWNER_EMAIL};
 const origin='https://test.invalid';
 const req=async(path,body,headers={})=>{const r=await worker.fetch(new Request(origin+'/api/'+path,{method:body?'POST':'GET',headers:{Origin:origin,...headers},body:body?JSON.stringify(body):undefined}),env);return {s:r.status,j:await r.json()};};
 const sig=(secret,text)=>createHmac('sha256',secret).update(text).digest('hex');
 assert.equal((await req('admin')).s,401);
 let route=(await req('catalogue')).j.routes[0];
 assert.equal((await req('admin/route',{...route,approved:true},head)).s,200);
 await req('admin/settings',{brand:'Example',phone:'9999999999',policy:'Example terms'},head);
 const date=new Date(Date.now()+3*86400000).toISOString().slice(0,10);
 const slot={route:route.id,time:date+'T12:00',vehicle:'CAR-1',blockMinutes:120};
 assert.equal((await req('admin/slot',slot,head)).s,200);
 assert.equal((await req('admin/slot',{...slot,time:date+'T13:00'},head)).s,409);
 const released=(await req('slots?route='+route.id+'&date='+date)).j[0];
 const a={slot:released.id,fare:route.fare,terms:route.terms,policy:'Example terms',rider:'Example',phone:'9999999999',pickup:'Airport',dropoff:'Hotel',passengers:2};
 let count=0;const pay={id:'pay_Test1',amount:route.fare*100,currency:'INR',status:'captured'};
 t.mock.method(globalThis,'fetch',async(url)=>Response.json(url.endsWith('/orders')?{id:'order_'+(++count)}:pay));
 assert.equal((await req('order',{...a,fare:1})).s,409);
 const o=(await req('order',a)).j;
 assert.ok(o.order);assert.equal((await req('order',a)).s,409);
 assert.equal((await req('booking?id='+o.id)).s,404);
 assert.equal((await req('admin/close',{id:released.id},head)).s,409);
 await env.DB.prepare('UPDATE bookings SET expires=0 WHERE id=?').bind(o.id).run();
 const second=(await req('order',a)).j;
 pay.order_id=second.order;
 const verification={id:second.id,payment:pay.id,signature:sig(env.RAZORPAY_KEY_SECRET,second.order+'|'+pay.id)};
 assert.equal((await req('verify',verification,{'X-Booking-Token':second.token})).j.status,'confirmed');
 const event={event:'payment.captured',payload:{payment:{entity:{...pay,id:'pay_Test2',order_id:o.order}}}};
 const headers={'x-razorpay-signature':sig(env.RAZORPAY_WEBHOOK_SECRET,JSON.stringify(event))};
 assert.equal((await req('webhook',event,headers)).s,200);assert.equal((await req('webhook',event,headers)).s,200);
 assert.equal((await req('booking?id='+o.id,undefined,{'X-Booking-Token':o.token})).j.status,'payment_review');
 assert.equal((await req('slots?route='+route.id+'&date='+date)).j.length,0);
});
